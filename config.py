def load_user_pool() -> list:
    """读取用户配置文件中的股票池（若存在）"""
    if not os.path.exists(CONFIG_FILE):
        return []
    try:
        with open(CONFIG_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
        pool = [(str(x[0]), str(x[1])) for x in data.get("pool", []) if len(x) >= 2]
        return pool
    except Exception:
        return []
